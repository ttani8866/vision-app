// 簡略化した大陸シルエット（正距円筒図法、viewBox 1000x500）と投影関数。
// AtlasMap と FlightTransition で共有する。

export const MAP_W = 1000;
export const MAP_H = 500;

export function project(lat: number, lng: number): { x: number; y: number } {
  return {
    x: ((lng + 180) / 360) * MAP_W,
    y: ((90 - lat) / 180) * MAP_H,
  };
}

